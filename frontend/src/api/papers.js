import request from './request'

export const getPapers = (params = {}) => request.get('/papers/', { params })
export const getPaper = (id) => request.get(`/papers/${id}/`)
export const favoritePaper = (id) => request.post(`/papers/${id}/favorite/`)
export const unfavoritePaper = (id) => request.delete(`/papers/${id}/favorite/`)
export const getPaperDateCounts = (params = {}) => request.get('/papers/date_counts/', { params })
export const getPaperDashboardStats = (params = {}) => request.get('/papers/dashboard-stats/', { params })
export const updatePaperAbstracts = (data) => request.post('/papers/update-abstracts/', data, { timeout: 300000 })
export const getAbstractUpdateActive = () => request.get('/tasks/abstract-update/active/')
export const getAbstractUpdateStatus = (taskId) => request.get(`/tasks/abstract-update/${taskId}/`)
export const markZoteroImported = (id) => request.post(`/papers/${id}/zotero-imported/`)
export const unmarkZoteroImported = (id) => request.delete(`/papers/${id}/zotero-imported/`)
export const getLowScorePapers = (params = {}) => request.get('/papers/low-score/', { params })
export const bulkSoftDeletePapers = (ids) => request.post('/papers/bulk-soft-delete/', { ids })
export const bulkRestorePapers = (ids) => request.post('/papers/bulk-restore/', { ids })
export const bulkRescorePapers = (ids) => request.post('/papers/bulk-rescore/', { ids }, { timeout: 300000 })
export const softDeletePaper = (id) => request.post(`/papers/${id}/soft-delete/`)
export const restorePaper = (id) => request.post(`/papers/${id}/restore/`)
export const rescorePaper = (id) => request.post(`/papers/${id}/rescore/`, {}, { timeout: 300000 })
export const summarizePaper = (id, force = false) => request.post(`/papers/${id}/ai-summary/`, { force }, { timeout: 60000 })
export const markPaperIrrelevant = (id) => request.post(`/papers/${id}/mark-irrelevant/`)
